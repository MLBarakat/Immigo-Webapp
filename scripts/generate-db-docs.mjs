#!/usr/bin/env node
/**
 * Generate docs/DATABASE.md from a migrated local Supabase database.
 *
 * The output is deterministic so `npm run docs:db:check` can fail when a
 * migration changes the schema without regenerating documentation.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const { Client } = pg;
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'docs', 'DATABASE.md');
const checkOnly = process.argv.includes('--check');
const connectionString =
  process.env.SUPABASE_DB_URL ||
  process.env.DATABASE_URL ||
  'postgresql://postgres:postgres@127.0.0.1:54322/postgres';

function cell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function code(value) {
  return `\`${String(value ?? '').replaceAll('`', "'")}\``;
}

async function main() {
  const client = new Client({ connectionString });
  await client.connect();

  const lines = [];
  lines.push('# ImmiGO Database Reference');
  lines.push('');
  lines.push('> Generated by `npm run docs:db` from a migrated local database. Do not edit by hand.');
  lines.push('> Run `npm run docs:db:check` to verify this file matches the migrations.');
  lines.push('');

  try {
    const { rows: migrations } = await client.query(`
      select version, name
      from supabase_migrations.schema_migrations
      order by version
    `);
    lines.push('## Migrations');
    lines.push('');
    lines.push('| Version | Name |');
    lines.push('| --- | --- |');
    for (const migration of migrations) {
      lines.push(`| ${cell(migration.version)} | ${cell(migration.name)} |`);
    }
    lines.push('');

    const { rows: tables } = await client.query(`
      select c.oid, c.relname, c.relrowsecurity
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind in ('r', 'p')
      order by c.relname
    `);

    lines.push('## Tables');
    lines.push('');
    for (const table of tables) {
      lines.push(`### ${code(`public.${table.relname}`)}`);
      lines.push('');
      lines.push(`Row level security: **${table.relrowsecurity ? 'enabled' : 'DISABLED'}**`);
      lines.push('');

      const { rows: columns } = await client.query(
        `
          select a.attname as column_name,
                 format_type(a.atttypid, a.atttypmod) as data_type,
                 not a.attnotnull as is_nullable,
                 pg_get_expr(d.adbin, d.adrelid) as column_default
          from pg_attribute a
          left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
          where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped
          order by a.attnum
        `,
        [table.oid],
      );
      lines.push('| Column | Type | Nullable | Default |');
      lines.push('| --- | --- | --- | --- |');
      for (const column of columns) {
        lines.push(
          `| ${code(column.column_name)} | ${code(column.data_type)} | ${
            column.is_nullable ? 'yes' : 'no'
          } | ${column.column_default ? code(column.column_default) : ''} |`,
        );
      }
      lines.push('');

      const { rows: policies } = await client.query(
        `
          select policyname, cmd, array_to_string(roles, ', ') as roles, qual, with_check
          from pg_policies
          where schemaname = 'public' and tablename = $1
          order by policyname
        `,
        [table.relname],
      );
      if (policies.length > 0) {
        lines.push('Policies:');
        lines.push('');
        lines.push('| Policy | Command | Roles | USING | WITH CHECK |');
        lines.push('| --- | --- | --- | --- | --- |');
        for (const policy of policies) {
          lines.push(
            `| ${cell(policy.policyname)} | ${cell(policy.cmd)} | ${cell(
              policy.roles,
            )} | ${policy.qual ? code(policy.qual) : ''} | ${
              policy.with_check ? code(policy.with_check) : ''
            } |`,
          );
        }
        lines.push('');
      }

      const { rows: foreignKeys } = await client.query(
        `
          select conname, pg_get_constraintdef(oid) as definition
          from pg_constraint
          where conrelid = $1 and contype = 'f'
          order by conname
        `,
        [table.oid],
      );
      if (foreignKeys.length > 0) {
        lines.push('Foreign keys:');
        lines.push('');
        for (const key of foreignKeys) {
          lines.push(`- ${code(key.conname)}: ${code(key.definition)}`);
        }
        lines.push('');
      }

      const { rows: indexes } = await client.query(
        `
          select indexname, indexdef
          from pg_indexes
          where schemaname = 'public' and tablename = $1
          order by indexname
        `,
        [table.relname],
      );
      if (indexes.length > 0) {
        lines.push('Indexes:');
        lines.push('');
        for (const index of indexes) {
          lines.push(`- ${code(index.indexdef)}`);
        }
        lines.push('');
      }
    }

    const { rows: views } = await client.query(`
      select c.oid, c.relname, coalesce(c.reloptions, array[]::text[]) as reloptions
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind = 'v'
      order by c.relname
    `);

    lines.push('## Views');
    lines.push('');
    for (const view of views) {
      const securityInvoker = view.reloptions.includes('security_invoker=true');
      lines.push(`### ${code(`public.${view.relname}`)}`);
      lines.push('');
      lines.push(`Security invoker: **${securityInvoker ? 'yes' : 'NO'}**`);
      lines.push('');
      const { rows: columns } = await client.query(
        `
          select a.attname as column_name, format_type(a.atttypid, a.atttypmod) as data_type
          from pg_attribute a
          where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped
          order by a.attnum
        `,
        [view.oid],
      );
      lines.push('| Column | Type |');
      lines.push('| --- | --- |');
      for (const column of columns) {
        lines.push(`| ${code(column.column_name)} | ${code(column.data_type)} |`);
      }
      lines.push('');
    }

    const { rows: functions } = await client.query(`
      select p.oid::regprocedure::text as signature,
             pg_get_function_result(p.oid) as returns,
             p.prosecdef as security_definer,
             coalesce(array_to_string(p.proconfig, ', '), '') as config,
             has_function_privilege('anon', p.oid, 'EXECUTE') as anon_execute,
             has_function_privilege('authenticated', p.oid, 'EXECUTE') as authenticated_execute
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public'
      order by 1
    `);

    lines.push('## Functions');
    lines.push('');
    lines.push('| Function | Returns | Security | search_path | anon EXECUTE | authenticated EXECUTE |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const fn of functions) {
      const searchPath = (fn.config ?? '')
        .split(', ')
        .find((setting) => setting.startsWith('search_path='))
        ?.slice('search_path='.length);
      lines.push(
        `| ${code(fn.signature)} | ${code(fn.returns)} | ${
          fn.security_definer ? 'definer' : 'invoker'
        } | ${searchPath === undefined ? 'not pinned' : code(searchPath || 'empty')} | ${
          fn.anon_execute ? 'YES' : 'no'
        } | ${fn.authenticated_execute ? 'yes' : 'no'} |`,
      );
    }
    lines.push('');
  } finally {
    await client.end();
  }

  const content = `${lines.join('\n')}\n`;

  if (checkOnly) {
    if (!existsSync(outputPath)) {
      console.error('docs/DATABASE.md is missing. Run `npm run docs:db`.');
      process.exitCode = 1;
      return;
    }
    const existing = readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n');
    if (existing !== content) {
      console.error('docs/DATABASE.md is stale. Run `npm run docs:db` and commit the result.');
      process.exitCode = 1;
      return;
    }
    console.log('docs/DATABASE.md is up to date.');
    return;
  }

  writeFileSync(outputPath, content, 'utf8');
  console.log(`Wrote ${outputPath}`);
}

main().catch((error) => {
  console.error('Could not generate database documentation. Is the local Supabase database up?');
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
